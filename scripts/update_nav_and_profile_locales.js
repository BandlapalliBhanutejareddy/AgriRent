// We will update build_clean_localizations.js by merging newKeys into each lang map
for (const lang of ['en', 'te', 'hi', 'ta', 'kn']) {
  const langObjMatch = new RegExp(`(${lang}:\\s*\\{[\\s\\S]*?\\n\\s*\\})`, 'g');
  scriptContent = scriptContent.replace(langObjMatch, (match, p1) => {
    let lines = [];
    for (const [k, v] of Object.entries(newKeys[lang])) {
      if (!p1.includes(`${k}:`)) {
        lines.push(`    ${k}: '${v.replace(/'/g, "\\'")}',`);
      }
    }
    if (lines.length > 0) {
      return p1.replace(/\n\s*\}$/, ',\n' + lines.join('\n') + '\n  }');
    }
    return match;
  });
}

fs.writeFileSync(scriptPath, scriptContent, 'utf8');
console.log('Updated build_clean_localizations.js with new keys');
